// Write a program to check whether a number is even or odd.

let num = 5;

if (num % 2 === 0) {
  console.log("Even number", num);
} else {
  console.log("Odd number", num);
}



for (let i = 1; i <= 10; i++) {
  if (i % 2 === 0) {
    console.log(i, "Even number");
  } else {
    console.log(i, "odd number");
  }
}
