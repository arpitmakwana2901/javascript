// Write a program to find the largest of three numbers.

let num1 = 10;
let num2 = 55;
let num3 = 25;

if (num1 > num2 && num1 > num3) {
  console.log(num1 + " is the largest");
} else if (num2 >= num1 && num2 >= num3) {
  console.log(num2 + " is the largest");
} else {
  console.log(num3 + " is the largest");
}
